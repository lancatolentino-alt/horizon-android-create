/// TFC's `Cellular2D`: jittered Voronoi cells, with the nearest and second-nearest centre.
#[derive(Clone, Debug)]
pub struct Cellular2D {
    jitter: f64,
    seed: i32,
    sample: i32,
    frequency: f64,
}

impl Cellular2D {
    pub fn new(seed: i64) -> Self {
        Self::with(seed, 0.43701595f32, 1)
    }
    pub fn with_sample(seed: i64, sample: i32) -> Self {
        Self::with(seed, 0.43701595f32, sample)
    }
    pub fn with(seed: i64, jitter: f32, sample: i32) -> Self {
        Cellular2D {
            seed: long2int(seed),
            frequency: 1.0,
            jitter: jitter as f64,
            sample,
        }
    }
    pub fn spread(mut self, scale: f64) -> Self {
        self.frequency *= scale;
        self
    }
    pub fn noise(&self, x: f64, y: f64) -> f64 {
        self.cell(x, y).noise
    }
    pub fn cell(&self, x: f64, y: f64) -> Cell {
        let x = x * self.frequency;
        let y = y * self.frequency;
        let xr = fast_floor(x);
        let yr = fast_floor(y);
        let mut distance0 = f64::MAX;
        let mut distance1 = f64::MAX;
        let mut angle0 = -1.0f64;
        let (mut this_x, mut this_y) = (0.0f64, 0.0f64);
        let (mut neighbor_x, mut neighbor_y) = (0.0f64, 0.0f64);
        let mut closest_hash = 0i32;
        let (mut no_jitter_x, mut no_jitter_y) = (0i32, 0i32);
        let mut x_primed = xr.wrapping_sub(self.sample).wrapping_mul(PRIME_X);
        let y_primed_base = yr.wrapping_sub(self.sample).wrapping_mul(PRIME_Y);
        for xi in (xr - self.sample)..=(xr + self.sample) {
            let mut y_primed = y_primed_base;
            for yi in (yr - self.sample)..=(yr + self.sample) {
                let hash = hash2(self.seed, x_primed, y_primed);
                let idx = (hash & (255 << 1)) as usize;
                let vec_x = xi as f64 + RAND_VECS_2D[idx] as f64 * self.jitter;
                let vec_y = yi as f64 + RAND_VECS_2D[idx | 1] as f64 * self.jitter;
                let dx = vec_x - x;
                let dy = vec_y - y;
                let new_angle = diamond_angle(dx, dy);
                let new_distance = dx * dx + dy * dy;
                let old_dist1 = distance1;
                distance1 = fmax(fmin(distance1, new_distance), distance0);
                if new_distance < distance0 {
                    distance0 = new_distance;
                    angle0 = new_angle;
                    closest_hash = hash;
                    neighbor_x = this_x;
                    neighbor_y = this_y;
                    this_x = vec_x;
                    this_y = vec_y;
                    no_jitter_x = xi;
                    no_jitter_y = yi;
                } else if distance1 != old_dist1 {
                    neighbor_x = vec_x;
                    neighbor_y = vec_y;
                }
                y_primed = y_primed.wrapping_add(PRIME_Y);
            }
            x_primed = x_primed.wrapping_add(PRIME_X);
        }
        Cell {
            x: this_x / self.frequency,
            y: this_y / self.frequency,
            cx: no_jitter_x,
            cy: no_jitter_y,
            nx: neighbor_x / self.frequency,
            ny: neighbor_y / self.frequency,
            f1: distance0,
            f2: distance1,
            noise: (closest_hash as f32 * (1.0f32 / 2147483648.0f32)) as f64,
            angle: angle0,
        }
    }
    /// `then`: a noise from a function of the cell.
    pub fn then(self, f: impl Fn(&Cell) -> f64 + Send + Sync + 'static) -> Noise2D {
        Noise2D::new(move |x, y| f(&self.cell(x, y)))
    }
}

/// TFC's `Cellular1D`: the hash value of the nearest jittered point on a line.
#[derive(Clone, Debug)]
pub struct Cellular1D {
    jitter: f64,
    seed: i32,
    frequency: f64,
}

impl Cellular1D {
    pub fn new(seed: i64) -> Self {
        Cellular1D {
            seed: long2int(seed),
            frequency: 1.0,
            jitter: 0.43701595f32 as f64,
        }
    }
    pub fn spread(mut self, scale: f64) -> Self {
        self.frequency *= scale;
        self
    }
    /// `Cellular1D.noise(x)`: the cell's hash value in `[-1, 1)`.
    pub fn noise(&self, x: f64) -> f64 {
        let x = x * self.frequency;
        let xr = fast_floor(x);
        let mut distance0 = f64::MAX;
        let mut distance1 = f64::MAX;
        let mut closest_hash = 0i32;
        let mut x_primed = xr.wrapping_sub(1).wrapping_mul(PRIME_X);
        for xi in (xr - 1)..=(xr + 1) {
            let hash = (self.seed ^ x_primed).wrapping_mul(0x27d4eb2d);
            let idx = (hash & (255 << 1)) as usize;
            let vec_x = xi as f64 + RAND_VECS_2D[idx] as f64 * self.jitter;
            let new_distance = vec_x - x;
            distance1 = fmax(fmin(distance1, new_distance), distance0);
            if new_distance < distance0 {
                distance0 = new_distance;
                closest_hash = hash;
            }
            x_primed = x_primed.wrapping_add(PRIME_X);
        }
        (closest_hash as f32 * (1.0f32 / 2147483648.0f32)) as f64
    }
}

fn fmin(a: f64, b: f64) -> f64 {
    if a < b { a } else { b }
}
fn fmax(a: f64, b: f64) -> f64 {
    if a > b { a } else { b }
}

/// TFC's `Noise2D` interface: a function of `(x, z)` with combinators that wrap it.
#[derive(Clone)]
pub struct Noise2D(std::sync::Arc<dyn Fn(f64, f64) -> f64 + Send + Sync>);

impl Noise2D {
    pub fn new(f: impl Fn(f64, f64) -> f64 + Send + Sync + 'static) -> Self {
        Noise2D(std::sync::Arc::new(f))
    }
    pub fn constant(c: f64) -> Self {
        Self::new(move |_, _| c)
    }
    pub fn from_simplex(n: OpenSimplex2D) -> Self {
        Self::new(move |x, z| n.noise(x, z))
    }
    pub fn noise(&self, x: f64, z: f64) -> f64 {
        (self.0)(x, z)
    }
    /// Default `octaves`: layers of itself at doubling scale.
    pub fn octaves(self, octaves: usize) -> Self {
        let frequency: Vec<f64> = (0..octaves).map(|i| (1i32 << i) as f64).collect();
        let amplitude: Vec<f64> = (0..octaves)
            .map(|i| 0.5f32.powi((octaves - i) as i32) as f64)
            .collect();
        Self::new(move |x, y| {
            let mut value = 0.0;
            for i in 0..octaves {
                value += self.noise(x / frequency[i], y / frequency[i]) * amplitude[i];
            }
            value
        })
    }
    pub fn ridged(self) -> Self {
        Self::new(move |x, y| {
            let mut v = self.noise(x, y);
            v = if v < 0.0 { -v } else { v };
            (1.0f32 as f64) - 2.0f32 as f64 * v
        })
    }
    pub fn abs(self) -> Self {
        Self::new(move |x, y| self.noise(x, y).abs())
    }
    pub fn terraces(self, levels: i32) -> Self {
        Self::new(move |x, y| {
            let value = 0.5f32 as f64 * self.noise(x, y) + 0.5f32 as f64;
            let rounded = (value * levels as f64) as i32 as f64;
            (rounded * 2.0f32 as f64) / levels as f64 - 1.0f32 as f64
        })
    }
    pub fn spread(self, scale: f64) -> Self {
        Self::new(move |x, y| self.noise(x * scale, y * scale))
    }
    pub fn scaled(self, min: f64, max: f64) -> Self {
        self.scaled4(-1.0, 1.0, min, max)
    }
    pub fn scaled4(self, old_min: f64, old_max: f64, min: f64, max: f64) -> Self {
        let scale = (max - min) / (old_max - old_min);
        let shift = min - old_min * scale;
        self.affine(scale, shift)
    }
    pub fn affine(self, scale: f64, shift: f64) -> Self {
        Self::new(move |x, y| self.noise(x, y) * scale + shift)
    }
    pub fn clamped_scaled(self, min: f64, max: f64) -> Self {
        let (old_min, old_max) = (-1.0, 1.0);
        let scale = (max - min) / (old_max - old_min);
        let shift = min - old_min * scale;
        Self::new(move |x, y| (self.noise(x, y) * scale + shift).clamp(min, max))
    }
    /// `clampedScaled(oldMin, oldMax, min, max)`.
    pub fn clamped_scaled4(self, old_min: f64, old_max: f64, min: f64, max: f64) -> Self {
        let scale = (max - min) / (old_max - old_min);
        let shift = min - old_min * scale;
        Self::new(move |x, y| (self.noise(x, y) * scale + shift).clamp(min, max))
    }
    pub fn clamped(self, min: f64, max: f64) -> Self {
        Self::new(move |x, y| self.noise(x, y).clamp(min, max))
    }
    pub fn add(self, other: Noise2D) -> Self {
        Self::new(move |x, y| self.noise(x, y) + other.noise(x, y))
    }
    pub fn add_constant(self, c: f64) -> Self {
        Self::new(move |x, y| self.noise(x, y) + c)
    }
    pub fn min(self, other: Noise2D) -> Self {
        Self::new(move |x, y| self.noise(x, y).min(other.noise(x, y)))
    }
    pub fn max(self, other: Noise2D) -> Self {
        Self::new(move |x, y| self.noise(x, y).max(other.noise(x, y)))
    }
    pub fn lazy_product(self, other: Noise2D) -> Self {
        Self::new(move |x, y| {
            let v = self.noise(x, y);
            if v == 0.0 { 0.0 } else { v * other.noise(x, y) }
        })
    }
    pub fn map(self, f: impl Fn(f64) -> f64 + Send + Sync + 'static) -> Self {
        Self::new(move |x, y| f(self.noise(x, y)))
    }
    pub fn ease_in(
        self,
        start: f64,
        end: f64,
        min_scale: f64,
        max_scale: f64,
        easing: Noise2D,
    ) -> Self {
        Self::new(move |x, z| {
            clamped_map(easing.noise(x, z), start, end, min_scale, max_scale) * self.noise(x, z)
        })
    }
    pub fn cliff_map(self, compare: Noise2D, addend: Noise2D) -> Self {
        Self::new(move |x, z| {
            let n = self.noise(x, z);
            if n > compare.noise(x, z) {
                n + addend.noise(x, z)
            } else {
                n
            }
        })
    }
    pub fn sloped_cliff_map(self, compare: Noise2D, addend: Noise2D, slope: Noise2D) -> Self {
        Self::new(move |x, z| {
            let noise = self.noise(x, z);
            let compare = compare.noise(x, z);
            let addend = addend.noise(x, z);
            let slope = slope.noise(x, z);
            if noise > compare + addend {
                noise + addend
            } else if noise > compare {
                noise + ((noise - compare) * slope).min(addend)
            } else {
                noise
            }
        })
    }
    /// `warped(OpenSimplex2D)`: samples `self` at the point the warp noise displaces `(x, z)` to.
    pub fn warped(self, warp: OpenSimplex2D) -> Self {
        Self::new(move |x, z| {
            let (wx, wz) = warp.warp(x, z);
            self.noise(wx, wz)
        })
    }
    pub fn stretch_z(self, stretch: f64) -> Self {
        Self::new(move |x, z| self.noise(x, z / stretch))
    }
    pub fn stretch_x(self, stretch: f64) -> Self {
        Self::new(move |x, z| self.noise(x / stretch, z))
    }
}

