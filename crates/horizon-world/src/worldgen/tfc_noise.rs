/// `HashCommon.long2int` of fastutil, which TFC uses to fold a `long` seed.
pub fn long2int(l: i64) -> i32 {
    (l ^ ((l as u64) >> 32) as i64) as i32
}

/// `Helpers.diamondAngle`: an angle in `[0, 4]` from a vector.
pub fn diamond_angle(x: f64, y: f64) -> f64 {
    if y >= 0.0 {
        if x >= 0.0 {
            y / (x + y)
        } else {
            1.0 - x / (-x + y)
        }
    } else if x < 0.0 {
        2.0 - y / (-x - y)
    } else {
        3.0 + x / (x - y)
    }
}

/// `Mth.clampedMap` (vanilla): maps `value` from `[from_min, from_max]` to `[to_min, to_max]`, clamped.
pub fn clamped_map(value: f64, from_min: f64, from_max: f64, to_min: f64, to_max: f64) -> f64 {
    let t = (value - from_min) / (from_max - from_min);
    if t < 0.0 {
        to_min
    } else if t > 1.0 {
        to_max
    } else {
        to_min + t * (to_max - to_min)
    }
}

/// One Voronoi cell, as TFC's `Cellular2D.Cell` record.
#[derive(Clone, Copy, Debug, PartialEq)]
