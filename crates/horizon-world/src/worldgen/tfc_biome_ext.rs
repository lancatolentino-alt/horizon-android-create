//! TerraFirmaCraft's biome extensions (`TFCBiomes` + `BiomeBuilder`, EUPL 1.2): for each of the
//! 125 biomes, in id order, its height noise, carving noise, blend types and flags.
//! Generated from the Java source; the surface builder names are kept for a later stage.

use super::tfc_biome_noise::*;
use super::tfc_noise::Noise2D;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BiomeBlendType {
    Land,
    Ocean,
    Lake,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RiverBlendType {
    None,
    Banked,
    TallBanked,
    Floodplain,
    Wide,
    WideDeep,
    Canyon,
    TallCanyon,
    Talus,
    Terraces,
    Cave,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ShoreBlendType {
    None,
    Classic,
    Sandy,
    Embayments,
    UpperTerrace,
    LowerTerrace,
    SetbackCliffs,
    Dunes,
    RockyShores,
    SeaStacks,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Carving {
    None,
    UndergroundLakes,
    Cenotes,
}

/// `AquiferLookahead`: where the aquifer thinks the surface is.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum AquiferHeight {
    /// The column's own height.
    Surface,
    /// The column's height plus an offset.
    Offset(f64),
    /// `SEA_LEVEL_Y - 16`, for carved biomes.
    SeaMinus16,
}

pub struct BiomeExtension {
    pub name: &'static str,
    pub height: Option<fn(i64) -> Noise2D>,
    pub carving: Carving,
    pub surface: &'static str,
    pub aquifer: AquiferHeight,
    pub blend: BiomeBlendType,
    pub river: RiverBlendType,
    pub shore_blend: ShoreBlendType,
    pub salty: bool,
    pub cinder_cones: bool,
    pub tuff_rings: bool,
    pub tuyas: bool,
    pub atolls: bool,
    pub stratovolcanoes: bool,
    pub feature_frequency: f32,
    pub feature_base_height: i32,
    pub feature_scale_height: i32,
    pub feature_ice: bool,
    pub spawnable: bool,
    pub rivers: bool,
    pub shore: bool,
    pub shore_base_height: i32,
    pub sandy_river_shores: bool,
}

impl BiomeExtension {
    /// `noiseFactory.apply(seed)`: the column sampler, or `None` for biomes without height (rivers).
    pub fn sampler(&self, seed: i64) -> Option<Box<dyn BiomeNoiseSampler>> {
        let height = self.height?(seed);
        Some(match self.carving {
            Carving::None => sampler_from_height_noise(height),
            Carving::UndergroundLakes => underground_lakes(seed, height),
            Carving::Cenotes => cenotes(seed, height),
        })
    }
}

