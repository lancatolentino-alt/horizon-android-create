    #[test]
    fn biome_height_noises_match_java_bit_for_bit() {
        let mut checked = 0;
        for line in JAVA.lines() {
            let mut parts = line.split(' ');
            let name = parts.next().unwrap();
            let ext = extensions().iter().find(|e| e.name == name).unwrap();
            let noise = (ext.height.unwrap())(4242424242);
            for ((x, z), expected) in POINTS.iter().zip(parts) {
                let bits = noise.noise(*x, *z).to_bits();
                assert_eq!(format!("{bits:x}"), expected, "{name} at ({x}, {z})");
            }
            checked += 1;
        }
        assert_eq!(checked, 124);
        assert_eq!(
            extensions().iter().filter(|e| e.height.is_none()).count(),
            1
        );
    }
